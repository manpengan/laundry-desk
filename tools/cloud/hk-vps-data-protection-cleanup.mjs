import { CloudReleaseError } from "./hk-vps-release-core.mjs";

const OPERATION_RETENTION_FAILURES = new Set([
  "CLOUD_DATA_SHADOW_DROP_FAILED",
  "CLOUD_DATA_STAGING_CREATE_FAILED",
  "CLOUD_DATA_STAGING_INVALID",
  "CLOUD_DATA_STAGING_CLEANUP_FAILED",
  "CLOUD_DATA_OFFSITE_STAGING_CREATE_FAILED",
  "CLOUD_DATA_OFFSITE_CLEANUP_FAILED",
  "CLOUD_DATA_CODE_STAGING_COLLISION",
  "CLOUD_DATA_CODE_STAGING_CLEANUP_FAILED",
  "CLOUD_DATA_PHOTO_STAGING_COLLISION",
  "CLOUD_DATA_PHOTO_STAGING_CLEANUP_FAILED",
]);

export function dataProtectionFailureRequiresOperation(error) {
  return error instanceof CloudReleaseError && OPERATION_RETENTION_FAILURES.has(error.code);
}
