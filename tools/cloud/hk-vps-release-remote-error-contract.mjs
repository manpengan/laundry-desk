const SAFE_REMOTE_RELEASE_ERROR_CODE_SET = new Set(SAFE_REMOTE_RELEASE_ERROR_CODES);

export function safeRemoteReleaseErrorCodes() {
  return Object.freeze([...SAFE_REMOTE_RELEASE_ERROR_CODES]);
}

export function parseSafeRemoteReleaseErrorCode(stdout, stderr) {
  if (stdout !== "" || typeof stderr !== "string" || !stderr.endsWith("\n")) return null;
  const code = stderr.slice(0, -1);
  if (`${code}\n` !== stderr || !SAFE_REMOTE_RELEASE_ERROR_CODE_SET.has(code)) return null;
  return code;
}
